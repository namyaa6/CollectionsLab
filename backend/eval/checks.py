"""Run every deterministic check on one transcript.

python -m backend.eval.checks --transcript data/transcripts/v1_s0_seed42.json [--summarize]
No LLM call unless --summarize is passed (one call, JUDGE_MODEL).
"""
import argparse
import json
from pathlib import Path
from typing import Optional

from pydantic import ValidationError

from backend.agent.summarizer import summarize, summarize_offline
from backend.agent.summary_schema import CallSummary
from backend.eval.fact_checker import check_facts
from backend.eval.models import CheckResult
from backend.eval.outcome_check import check_outcome
from backend.eval.policy_check import check_policy
from backend.eval.retrieval_stats import retrieval_stats
from backend.eval.voice_linter import count_by_category, lint_transcript
from backend.scenarios.generator import Invoice, generate_scenarios
from backend.sim.transcript import Transcript

DEFAULT_POOL = 14  # scenarios generated by run_one before picking one


def _get_invoice_result(t: Transcript) -> Optional[dict]:
    for turn in t.turns:
        for call in turn.tool_calls:
            result = call.get("result") or {}
            if call.get("tool") == "get_invoice" and "invoice_id" in result:
                return result
    return None


def resolve_invoice(t: Transcript, pool: int = DEFAULT_POOL) -> tuple[Optional[Invoice], str, list[str]]:
    """Returns (invoice, source, notes). Order: stored, regenerated (id-checked), get_invoice, none."""
    if t.scenario is not None:
        return t.scenario.invoice, "stored", []
    notes = ["No scenario stored in this transcript (saved before M6)."]
    seen = _get_invoice_result(t)
    try:
        regenerated = generate_scenarios(pool, t.seed)[t.scenario_id].invoice
    except IndexError:
        regenerated = None
    if regenerated and seen and regenerated.invoice_id == seen["invoice_id"]:
        return regenerated, "regenerated", notes
    if regenerated and seen:
        notes.append(f"Regenerated invoice {regenerated.invoice_id} does not match the "
                     f"get_invoice result {seen['invoice_id']}; regenerated invoice ignored.")
    elif regenerated:
        notes.append("Agent never called get_invoice, so the regenerated invoice cannot be verified.")
    if seen:
        try:
            return Invoice.model_validate(seen), "get_invoice", notes
        except ValidationError:
            notes.append("The get_invoice result in the transcript is malformed.")
    notes.append("No trustworthy invoice found: fact check and policy check skipped.")
    return None, "none", notes


def run_all_checks(t: Transcript, summary: CallSummary, invoice: Optional[Invoice] = None,
                   pool: int = DEFAULT_POOL) -> CheckResult:
    notes: list[str] = []
    if invoice is not None:
        source = "provided"
    else:
        invoice, source, notes = resolve_invoice(t, pool)
    violations = lint_transcript(t)
    return CheckResult(
        invoice_source=source, summary_llm_used=summary.llm_used,
        voice_violations=violations, voice_counts=count_by_category(violations),
        facts=check_facts(t, invoice) if invoice else None,
        policy_violations=check_policy(t, invoice) if invoice else None,
        outcome=check_outcome(summary, t.expected_outcomes),
        retrieval=retrieval_stats(t), notes=notes)


def main(argv: Optional[list[str]] = None) -> None:
    p = argparse.ArgumentParser(description="Deterministic checks on one saved transcript")
    p.add_argument("--transcript", type=Path, required=True)
    p.add_argument("--summarize", action="store_true",
                   help="read the dialogue with the judge model (1 live LLM call)")
    p.add_argument("--pool", type=int, default=DEFAULT_POOL,
                   help="scenario pool size, only used for transcripts without a stored scenario")
    args = p.parse_args(argv)
    transcript = Transcript.load(args.transcript)
    if args.summarize:
        from backend.config import get_config  # imported here so the default path stays offline
        from backend.llm.client import LLMClient
        cfg = get_config()
        summary = summarize(transcript, LLMClient.from_config(cfg), cfg.judge_model)
    else:
        summary = summarize_offline(transcript)
    result = run_all_checks(transcript, summary, pool=args.pool)
    # ensure_ascii: snippets contain the rupee sign, which a Windows cp1252 console cannot print
    print(json.dumps(result.model_dump(mode="json"), indent=2, ensure_ascii=True))


if __name__ == "__main__":
    main()
