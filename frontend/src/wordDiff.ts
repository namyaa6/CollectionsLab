// Word-level diff of a self-check draft against the spoken final text.

export interface DiffPart {
  op: "same" | "add" | "del";
  text: string;
}

/**
 * Longest-common-subsequence diff over words. Words, not characters: a reviewer wants to see
 * "five hundred" replaced by "five thousand", not a scatter of single changed letters.
 * O(n*m) is fine for one spoken turn (a few dozen words).
 */
export function wordDiff(before: string, after: string): DiffPart[] {
  const a = before.split(/\s+/).filter(Boolean);
  const b = after.split(/\s+/).filter(Boolean);
  // lcs[i][j] = length of the LCS of a[i..] and b[j..]
  const lcs = Array.from({ length: a.length + 1 }, () => new Array<number>(b.length + 1).fill(0));
  for (let i = a.length - 1; i >= 0; i--) {
    for (let j = b.length - 1; j >= 0; j--) {
      lcs[i][j] = a[i] === b[j] ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
    }
  }

  const parts: DiffPart[] = [];
  const push = (op: DiffPart["op"], word: string) => {
    const last = parts[parts.length - 1];
    if (last && last.op === op) last.text += " " + word;
    else parts.push({ op, text: word });
  };
  let i = 0;
  let j = 0;
  while (i < a.length && j < b.length) {
    if (a[i] === b[j]) {
      push("same", a[i]);
      i++;
      j++;
    } else if (lcs[i + 1][j] >= lcs[i][j + 1]) {
      push("del", a[i++]);
    } else {
      push("add", b[j++]);
    }
  }
  while (i < a.length) push("del", a[i++]);
  while (j < b.length) push("add", b[j++]);
  return parts;
}
